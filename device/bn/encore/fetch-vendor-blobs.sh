# fetch-vendor-blobs.sh - put the proprietary PowerVR SGX530 driver files
# listed in proprietary-files.txt into vendor/bn/encore and generate the
# makefiles the build includes from there.
#
# usage (from anywhere in the tree):
#   device/bn/encore/fetch-vendor-blobs.sh             # from TheMuppets (GitHub)
#   device/bn/encore/fetch-vendor-blobs.sh --adb       # from a Nook Color running CM over adb
#   device/bn/encore/fetch-vendor-blobs.sh --dir PATH  # from an unpacked CM /system
#
# The files are the TI/Imagination SGX530 user-space driver that every CM
# release for the Nook Color shipped (CM 11 and the CM 12 vendor branch use
# identical copies).  They are proprietary, so they are not committed here.

set -e

DEVICE=encore
VENDOR=bn
MUPPETS_URL=https://github.com/TheMuppets/proprietary_vendor_bn
MUPPETS_BRANCH=cm-11.0

MY_DIR=$(cd "$(dirname "$0")" && pwd)
TOP=$(cd "$MY_DIR/../../.." && pwd)
OUTDIR=vendor/$VENDOR/$DEVICE
DEST=$TOP/$OUTDIR
FILES=$(grep -v '^\s*#' "$MY_DIR/proprietary-files.txt" | grep -v '^\s*$')

mode=muppets
case "$1" in
    --adb) mode=adb ;;
    --dir) mode=dir; SRCDIR=$2; [ -d "$SRCDIR" ] || { echo "no such directory: $SRCDIR"; exit 1; } ;;
    "") ;;
    *) sed -n '18,24p' "$0"; exit 1 ;;
esac

rm -rf "$DEST/proprietary"
mkdir -p "$DEST/proprietary"

case $mode in
muppets)
    TMP=$(mktemp -d)
    trap 'rm -rf "$TMP"' EXIT
    echo "Fetching $MUPPETS_URL ($MUPPETS_BRANCH) ..."
    git clone -q --depth 1 --filter=blob:none --sparse -b "$MUPPETS_BRANCH" \
        "$MUPPETS_URL" "$TMP/vendor"
    git -C "$TMP/vendor" sparse-checkout set "$DEVICE/proprietary"
    SRC="$TMP/vendor/$DEVICE/proprietary"
    ;;
adb)
    adb wait-for-device
    SRC=""
    ;;
dir)
    SRC=$SRCDIR
    ;;
esac

for f in $FILES; do
    mkdir -p "$DEST/proprietary/$(dirname $f)"
    if [ $mode = adb ]; then
        adb pull "/system/$f" "$DEST/proprietary/$f"
    else
        cp "$SRC/$f" "$DEST/proprietary/$f"
    fi
done

# ---------------------------------------------------------------------------
# Makefiles
# ---------------------------------------------------------------------------
HEADER="# Generated by device/$VENDOR/$DEVICE/fetch-vendor-blobs.sh - DO NOT EDIT"

cat > "$DEST/BoardConfigVendor.mk" <<EOF
$HEADER
EOF

{
    echo "$HEADER"
    echo
    echo "PRODUCT_COPY_FILES += \\"
    last=$(echo "$FILES" | tail -n 1)
    for f in $FILES; do
        sep=" \\"
        [ "$f" = "$last" ] && sep=""
        echo "    $OUTDIR/proprietary/$f:system/$f$sep"
    done
} > "$DEST/$DEVICE-vendor.mk"

echo
echo "Installed $(echo "$FILES" | wc -l) files into $OUTDIR"
