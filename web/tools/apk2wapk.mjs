#!/usr/bin/env node
// apk2wapk: converts an Android APK into a WAPK package for Android 5.0 for the web.
//
//   node tools/apk2wapk.mjs <app.apk> [--impl <dir>] [-o <out.wapk>]
//
// What is carried over from the APK (parsed with src/js/core/apk.js, i.e.
// AndroidManifest.xml + resources.arsc, resolved for an API 21 xxxhdpi phone):
// package name, version, SDK levels, permissions, application label, launcher
// icon and launchable activity, plus provenance (APK SHA-256, DEX/ABI list).
//
// What is NOT carried over: the Dalvik bytecode (classes*.dex) and native
// libraries. The browser port has no ART runtime, so the app's behaviour comes
// from a web implementation in --impl <dir>:
//   main.js     ES module: export default android => class extends android.App { ... }
//   style.css   optional, injected while the package is installed
//   wapk.json   optional overrides: { theme, label, fullscreen, permissions, minSdkVersion }
//   res/**      optional resources, available through android.resource(path)
// Without --impl a stub app is generated that explains this and shows the APK info.
import fs from 'node:fs';
import path from 'node:path';
import { readApk } from '../src/js/core/apk.js';
import { writeZip, sha256Hex } from '../src/js/core/zip.js';

const args = process.argv.slice(2);
const opt = (name, short) => { const i = args.findIndex(a => a === name || a === short); if (i < 0) return null; const v = args[i + 1]; args.splice(i, 2); return v; };
const implDir = opt('--impl', '-i');
const outArg = opt('--out', '-o');
const apkPath = args[0];
if (!apkPath) { console.error('usage: apk2wapk <app.apk> [--impl <dir>] [-o <out.wapk>]'); process.exit(2); }

const apk = await readApk(new Uint8Array(fs.readFileSync(apkPath)));
console.log(`[apk2wapk] ${apk.package} ${apk.versionName} (${apk.versionCode}) "${apk.label}" minSdk ${apk.minSdkVersion} targetSdk ${apk.targetSdkVersion}`);
console.log(`[apk2wapk] icon ${apk.iconPath || '(none)'}; ${apk.permissions.length} permissions; dex: ${apk.dexFiles.join(', ') || 'none'}; native ABIs: ${apk.nativeAbis.join(', ') || 'none'}`);

const overrides = implDir && fs.existsSync(path.join(implDir, 'wapk.json')) ? JSON.parse(fs.readFileSync(path.join(implDir, 'wapk.json'), 'utf8')) : {};
const files = [];
const add = (name, data) => files.push({ name, data: typeof data === 'string' ? new TextEncoder().encode(data) : new Uint8Array(data) });

if (implDir) {
  const walk = (dir, rel = '') => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const r = rel ? `${rel}/${e.name}` : e.name;
      if (e.isDirectory()) walk(path.join(dir, e.name), r);
      else if (r !== 'wapk.json' && !r.endsWith('.md')) add(r, fs.readFileSync(path.join(dir, e.name)));
    }
  };
  walk(implDir);
  if (!files.some(f => f.name === 'main.js')) { console.error('[apk2wapk] --impl directory must contain main.js'); process.exit(1); }
} else {
  add('main.js', `// Generated by apk2wapk: the APK's Dalvik code cannot run in the browser.
export default android => class extends android.App {
  onCreate(root) {
    const { h, ui, manifest } = android;
    root.append(h('div', { style: { position: 'absolute', inset: 0, display: 'flex', flexDirection: 'column', background: '#fafafa' } },
      ui.toolbar({ title: manifest.label }),
      h('div.page-content', { style: { padding: '16px', color: 'rgba(0,0,0,.7)', lineHeight: 1.5 } },
        h('p', 'This package was converted from an Android APK, but no web implementation was supplied.'),
        h('p', 'The original app is compiled to Dalvik bytecode, which this browser port cannot execute.'),
        h('p', manifest.package + ' ' + manifest.versionName))));
  }
};
`);
}

if (apk.icon) add('icon.png', apk.icon);
else add('icon.png', fs.readFileSync(new URL('../../packages/apps/Launcher3/res/mipmap-xxhdpi/ic_launcher_application.png', import.meta.url)));

const source = {
  converter: 'apk2wapk/1',
  convertedAt: new Date().toISOString(),
  apk: { file: path.basename(apkPath), sha256: apk.sha256, versionCode: apk.versionCode, launchableActivity: apk.launchableActivity,
    iconPath: apk.iconPath, dexFiles: apk.dexFiles, nativeAbis: apk.nativeAbis, permissions: apk.permissions },
  implementation: implDir ? 'web' : 'stub',
};
add('META-INF/SOURCE.json', JSON.stringify(source, null, 2));

const manifest = {
  wapk: 1,
  package: apk.package,
  label: overrides.label || apk.label,
  versionCode: apk.versionCode,
  versionName: apk.versionName,
  minSdkVersion: overrides.minSdkVersion || apk.minSdkVersion,
  targetSdkVersion: apk.targetSdkVersion,
  minRuntime: 1,
  // Only permissions that mean something in the browser runtime are requested;
  // the full APK list is kept in META-INF/SOURCE.json.
  permissions: overrides.permissions || apk.permissions,
  icon: 'icon.png',
  entry: 'main.js',
  styles: files.some(f => f.name === 'style.css') ? ['style.css'] : [],
  theme: overrides.theme || {},
  fullscreen: !!overrides.fullscreen,
  files: {},
};
for (const f of files) manifest.files[f.name] = await sha256Hex(f.data);
const out = await writeZip([{ name: 'WAPK-MANIFEST.json', data: JSON.stringify(manifest, null, 2) }, ...files]);
const outPath = outArg || `${apk.package}-${apk.versionName}.wapk`;
fs.mkdirSync(path.dirname(path.resolve(outPath)), { recursive: true });
fs.writeFileSync(outPath, out);
console.log(`[apk2wapk] wrote ${outPath} (${out.length} bytes, ${files.length + 1} entries, implementation: ${source.implementation})`);
